"""Regenerates the shared data files for the website and the backend.

Run after editing shared/strings.json OR the rule tables in backend/app/text.py / rules.py:
    python3 tools/sync_data.py
shared/nlp.json is GENERATED from the Python rule tables, so the website's offline engine
(website/magic/magic-engine.js) and the backend always use the same words, units and conversions.
"""
import json
import pathlib
import shutil
import sys

root = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / "backend"))
from app import rules as RU          # noqa: E402
from app import text as T            # noqa: E402

nlp = {
    "hindi": T.HINDI_WORDS,
    "stopwords": sorted(T.STOPWORDS),
    "unit_class": T.UNIT_CLASS,
    "label_word_class": T.LABEL_WORD_CLASS,
    "unit_canon": RU.UNIT_CANON,
    "conversions": {f"{a}|{b}": f for (a, b), f in RU.CONVERSIONS.items()},
    "key_words": sorted(RU.KEY_WORDS),
    "filler": sorted(RU.FILLER),
    "label_stop": sorted(RU.LABEL_STOP),
    "ambiguous_classes": sorted(RU.AMBIGUOUS_CLASSES),
    "elements": RU.ELEMENTS,
    "unit_re": T._UNIT,
    "num_re": T.NUM,
}
(root / "shared" / "nlp.json").write_text(json.dumps(nlp, ensure_ascii=False), encoding="utf-8")

# Backend gets the registry (built by tools/build_registry.js) and the strings.
shutil.copyfile(root / "shared" / "strings.json", root / "backend/app/data" / "strings.json")

# The website gets ONE self-contained data file, so the page works from any static host or preview.
registry = json.loads((root / "backend/app/data/registry.json").read_text(encoding="utf-8"))
strings = json.loads((root / "shared" / "strings.json").read_text(encoding="utf-8"))
js = "/* GENERATED by tools/sync_data.py. Do not edit by hand. */\nwindow.MAGIC_DATA=" + json.dumps(
    {"registry": registry, "nlp": nlp, "strings": strings}, ensure_ascii=False, separators=(",", ":")) + ";\n"
(root / "website/magic/magic-data.js").write_text(js, encoding="utf-8")
print("synced: backend strings.json, website/magic/magic-data.js (%d KB)" % (len(js) // 1024))
